# ---------------------------------------------------------------------------
# Guarantee every canonical ask matches its own family: if the authored
# pattern misses, add a literal alternative built from the ask's key words.
# ---------------------------------------------------------------------------
import re as _re

_LEAD = {"write", "code", "show", "show me", "make", "create", "build",
         "implement", "give", "give me", "help", "help me", "need", "want",
         "how", "do", "i", "to", "a", "an", "the", "me", "please", "print",
         "read", "convert", "calculate", "compute", "count", "find", "sort",
         "merge", "check", "parse", "validate", "reverse", "split", "join",
         "remove", "dedupe", "sample", "generate", "using", "with", "for"}

_TAIL = {"code", "function", "script", "program", "example", "demo",
         "snippet", "sample"}


def _phrase_from_ask(ask: str) -> str:
    words = [w for w in _re.findall(r"[a-z0-9#'.]+", ask.lower())]
    words[-1:] = [w.rstrip(".") for w in words[-1:]]
    while words and words[0] in _LEAD:
        words.pop(0)
    while words and words[-1] in _TAIL:
        words.pop()
    if not words or (len(words) < 2 and len(words[0]) < 6):
        return ""                      # one short word is too broad to match on
    return r"[\s\-]+".join(_re.escape(w) for w in words)


def _broaden(pattern: str, ask: str) -> str:
    if _re.search(pattern, ask, _re.I):
        return pattern
    alt = _phrase_from_ask(ask)
    return f"{pattern}|{alt}" if alt else pattern


EXTRA = [(n, _broaden(p, a), a, c) for n, p, a, c in EXTRA]
